const fs = require("node:fs");
const path = require("node:path");

const publicDirectory = path.join(process.cwd(), "public");
const portfolioDirectory = path.join(publicDirectory, "portfolio");
const activityProjectDirectory = path.join(publicDirectory, "activity-projects");
const outputFile = path.join(process.cwd(), "src/lib/portfolio-assets.generated.ts");
const imageExtensions = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif"]);

function visit(directory, assets) {
  const entries = fs.readdirSync(directory, { withFileTypes: true });
  const images = entries
    .filter((entry) => entry.isFile() && imageExtensions.has(path.extname(entry.name).toLowerCase()))
    .map((entry) => entry.name)
    .sort((left, right) => left.localeCompare(right, undefined, { numeric: true, sensitivity: "base" }));

  if (images.length > 0) {
    const relativeDirectory = path.relative(publicDirectory, directory).split(path.sep).join("/");
    assets[relativeDirectory] = images;
  }

  for (const entry of entries.filter((item) => item.isDirectory()).sort((left, right) => left.name.localeCompare(right.name))) {
    visit(path.join(directory, entry.name), assets);
  }
}

const assets = {};
visit(portfolioDirectory, assets);
const activityAssets = {};

if (fs.existsSync(activityProjectDirectory)) {
  visit(activityProjectDirectory, activityAssets);
}

const source = [
  "// This file is generated by scripts/generate-portfolio-assets.js. Do not edit manually.",
  "export const portfolioAssetFiles: Record<string, readonly string[]> = " + JSON.stringify(assets, null, 2) + " as const;",
  "export const activityProjectAssetFiles: Record<string, readonly string[]> = " + JSON.stringify(activityAssets, null, 2) + " as const;",
  "",
].join("\n");

fs.writeFileSync(outputFile, source);
